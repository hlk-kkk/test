"""Export tournament winners: migrate images and generate seed data."""

import asyncio
import json
import logging
import shutil
import uuid
from pathlib import Path

from .classifier import Category
from .data_loader import Candidate
from .llm_client import chat

logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
STORAGE_DIR = PROJECT_ROOT / "storage" / "templates"
SEED_FILE = PROJECT_ROOT / "backend" / "src" / "pictactic" / "db" / "system_templates.py"

METADATA_PROMPT = """Given this AI image generation prompt, create metadata for a template library.

Prompt:
{prompt_text}

Generate:
- title: Short descriptive title (max 50 chars, English)
- description: One-sentence description of what this prompt creates (max 200 chars, English)
- tags: 3-5 relevant tags (English, lowercase)

Output ONLY JSON:
{{"title": "...", "description": "...", "tags": ["...", "..."]}}"""


async def generate_metadata(
    candidates: list[Candidate],
    concurrency: int = 5,
) -> dict[str, dict]:
    """Generate title, description, tags for each candidate via LLM."""
    semaphore = asyncio.Semaphore(concurrency)
    results: dict[str, dict] = {}

    async def process_one(c: Candidate) -> None:
        prompt_preview = c.prompt_text[:1000] if len(c.prompt_text) > 1000 else c.prompt_text
        prompt = METADATA_PROMPT.format(prompt_text=prompt_preview)

        async with semaphore:
            try:
                response = await chat(
                    messages=[{"role": "user", "content": prompt}],
                    temperature=0.3,
                    max_tokens=512,
                )
                text = response.strip()
                if text.startswith("```"):
                    text = text.split("\n", 1)[1]
                    text = text.rsplit("```", 1)[0]
                results[c.tweet_id] = json.loads(text)
            except Exception:
                logger.exception("Failed to generate metadata for %s", c.tweet_id)
                results[c.tweet_id] = {
                    "title": f"Template {c.tweet_id[:8]}",
                    "description": "AI-generated image template",
                    "tags": [],
                }

    await asyncio.gather(*[process_one(c) for c in candidates])
    logger.info("Generated metadata for %d candidates", len(results))
    return results


def migrate_images(candidates: list[Candidate]) -> dict[str, list[str]]:
    """Copy winner images to storage/templates/{tweet_id}/. Returns {tweet_id: [url_paths]}."""
    url_map: dict[str, list[str]] = {}

    for c in candidates:
        dest_dir = STORAGE_DIR / c.tweet_id
        dest_dir.mkdir(parents=True, exist_ok=True)
        urls = []

        for src_path in c.image_paths:
            src = Path(src_path)
            if not src.exists():
                continue
            dest = dest_dir / src.name
            shutil.copy2(src, dest)
            urls.append(f"/static/templates/{c.tweet_id}/{src.name}")

        url_map[c.tweet_id] = urls

    logger.info("Migrated images for %d candidates to %s", len(candidates), STORAGE_DIR)
    return url_map


def generate_seed_module(
    candidates: list[Candidate],
    metadata: dict[str, dict],
    image_urls: dict[str, list[str]],
    categories: list[Category],
) -> None:
    """Generate backend/src/pictactic/db/system_templates.py."""
    cat_list = []
    for cat in categories:
        cat_list.append({
            "name": cat.name,
            "display_name": cat.display_name,
            "description": cat.description,
        })

    templates = []
    for c in candidates:
        meta = metadata.get(c.tweet_id, {})
        urls = image_urls.get(c.tweet_id, [])
        preview_url = urls[0] if urls else None

        templates.append({
            "id": f"system-{uuid.uuid4().hex[:12]}",
            "title": meta.get("title", f"Template {c.tweet_id[:8]}"),
            "description": meta.get("description", ""),
            "prompt_text": c.prompt_text,
            "category": c.category,
            "tags": meta.get("tags", []),
            "preview_image_url": preview_url,
            "all_image_urls": urls,
            "source_url": c.tweet_url,
            "source_author": c.author,
        })

    content = f'''"""System-preloaded templates — generated by template_tournament."""

# Auto-generated. Do not edit manually.

SYSTEM_CATEGORIES = {json.dumps(cat_list, indent=4, ensure_ascii=False)}

SYSTEM_TEMPLATES = {json.dumps(templates, indent=4, ensure_ascii=False)}
'''

    SEED_FILE.parent.mkdir(parents=True, exist_ok=True)
    SEED_FILE.write_text(content, encoding="utf-8")
    logger.info("Generated seed module at %s with %d templates", SEED_FILE, len(templates))
